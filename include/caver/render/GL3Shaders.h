    "//  3. 2.5D DYNAMIC POINT LIGHTS (fire sword, torches, trinkets, spells)\n"
    "// ============================================================================\n"
    "vec3 EvaluatePointLights25D(vec3 N, vec3 V, vec3 eyePos, vec3 albedo, float shadow, out vec3 pointSpecOut) {\n"
    "    vec3 pointLightRgb = vec3(0.0);\n"
    "    pointSpecOut = vec3(0.0);\n"
    "    for (int i = 0; i < 16; ++i) {\n"
    "        if (i >= u_pointLightCount) break;\n"
    "        float intensity = u_pointLightColor[i].a;\n"
    "        if (intensity < 0.005) continue;\n"
    "\n"
    "        vec3 lVec = u_pointLightPosRadius[i].xyz - eyePos;\n"
    "        vec3 lVec25D = vec3(lVec.x, lVec.y, lVec.z * 0.25);\n"
    "        float dist = length(lVec25D);\n"
    "        float radius = max(u_pointLightPosRadius[i].w, 1.0);\n"
    "        if (dist < radius) {\n"
    "            vec3 Lp = normalize(vec3(lVec.x, lVec.y, max(abs(lVec.z), 30.0)));\n"
    "            float ratio = clamp(dist / radius, 0.0, 1.0);\n"
    "            float window = clamp(1.0 - ratio * ratio, 0.0, 1.0);\n"
    "            // Cubic window attenuation: reaches zero smoothly with zero derivative at boundary\n"
    "            float atten = (window * window * window) / (1.0 + 1.2 * ratio * ratio);\n"
    "\n"
    "            vec3 lc = u_pointLightColor[i].rgb;\n"
    "            // Stable world-space position hash for gentle flame breathing (NO index hopping!)\n"
    "            float phase = dot(u_pointLightPosRadius[i].xyz, vec3(0.013, 0.017, 0.023));\n"
    "            float warm = smoothstep(0.0, 0.35, lc.r - lc.b);\n"
    "            float flickFreq = (u_biomeId == 6) ? 1.25 : 1.0;\n"
    "            float flickAmp  = (u_biomeId == 6) ? 1.30 : 1.0;\n"
    "            // Gentle organic flame breath (2.2Hz and 4.1Hz), never strobe\n"
    "            float flicker = 1.0 + warm * flickAmp * (0.035 * sin(u_time * 2.2 * flickFreq + phase) +\n"
    "                                                     0.020 * sin(u_time * 4.1 * flickFreq + phase * 1.6));\n"
    "\n"
    "            float pDiff = mix(0.35, 1.0, clamp(dot(N, Lp), 0.0, 1.0));\n"
    "            float shadowBoost = mix(1.40, 0.90, shadow);\n"
    "            vec3 lightCol = lc * shadowBoost * flicker;\n"
    "            pointLightRgb += albedo * lightCol * (pDiff * atten * 1.45);\n"
    "\n"
    "            vec3 Hp = normalize(Lp + V);\n"
    "            float pSpec = pow(max(dot(N, Hp), 0.0), 24.0) * atten * 0.30;\n"
    "            pointSpecOut += lightCol * pSpec;\n"
    "        }\n"
    "    }\n"
    "    return pointLightRgb;\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    vec4 tex = vec4(1.0);\n"
    "    if (u_texturingEnabled != 0) {\n"
    "        if (u_isShadowPass != 0 || u_lightingEnabled == 0)\n"
    "            tex = texture(u_texture, v_texcoord);\n"
    "        else\n"
    "            tex = SampleAlbedo(v_texcoord);\n"
    "        if (tex.a < 0.01) discard;\n"
    "    }\n"
    "    vec4 primary = (u_useVertexColor != 0) ? v_color : u_color;\n"
    "\n"
    "    // Shadow atlas depth pass: cut-out test only.\n"
    "    if (u_isShadowPass != 0) {\n"
    "        if (u_texturingEnabled != 0 && tex.a < 0.5) discard;\n"
    "        fragColor = vec4(1.0);\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    // ---------------------------------------------------------------- LIT WORLD\n"
    "    if (u_lightingEnabled != 0) {\n"
    "        vec3 N = (length(v_normal) > 0.001) ? normalize(v_normal) : vec3(0.0, 0.0, 1.0);\n"
    "        vec3 V = (length(v_eyePos) > 0.001) ? normalize(-v_eyePos) : vec3(0.0, 0.0, 1.0);\n"
    "\n"
    "        // ES1 FFP semantics: vertex colour and material diffuse multiply together.\n"
    "        vec3 vertCol = (u_useVertexColor != 0) ? v_color.rgb : vec3(1.0);\n"
    "        float vertAlpha = (u_useVertexColor != 0) ? v_color.a : 1.0;\n"
    "        vec3 matAmb  = min(u_matAmbient.rgb, vec3(0.85)) * vertCol;\n"
    "        vec3 matDiff = min(u_matDiffuse.rgb, vec3(0.90)) * vertCol;\n"
    "        float matAlpha = u_matDiffuse.a * vertAlpha;\n"
    "\n"
    "        vec3 baseAlbedo = tex.rgb * matDiff;\n"
    "        MaterialProps mat = ClassifyMaterial(baseAlbedo, v_worldNormal, u_shininess, u_biomeId);\n"
    "        ApplySurfaceRelief(baseAlbedo, N, v_worldNormal, v_eyePos, tex.a, mat, u_biomeId);\n"
    "\n"
    "        // Directional Sun/Moon Key Light: Use level's actual directional light if present\n"
    "        vec3 fallbackSun = normalize(vec3(-0.20, 0.90, 0.40));\n"
    "        vec3 L = (u_dirLightCount > 0 && length(u_dirLightDir[0]) > 0.1)\n"
    "                 ? normalize(u_dirLightDir[0] + vec3(0.0, 0.15, 0.30))\n"
    "                 : fallbackSun;\n"
    "        vec3 sunColor = (u_dirLightCount > 0)\n"
    "                      ? clamp(u_dirLightDiffuse[0].rgb, vec3(0.20), vec3(1.20))\n"
    "                      : vec3(0.88, 0.86, 0.84);\n"
    "\n"
    "        float nDotL = dot(N, L);\n"
    "        float shadowMix = (u_biomeId == 4) ? 0.55 : 0.68;\n"
    "        float shadow = mix(1.0, SampleSoftShadow(v_shadowCoord, max(nDotL, 0.0)), shadowMix);\n"
    "\n"
    "        // Overhang shade (subtle underside darkening)\n"
    "        float overhangShade = smoothstep(-0.80, 0.20, v_worldNormal.y);\n"
    "        shadow *= mix(0.75, 1.0, overhangShade);\n"
    "\n"
    "        // Soft wrap lighting (preserves smooth comic/fantasy curvature)\n"
    "        float wrap = 0.25;\n"
    "        float diffuseTerm = clamp((nDotL + wrap) / (1.0 + wrap), 0.0, 1.0);\n"
    "        float litDiffuse = diffuseTerm * shadow;\n"
    "\n"
    "        // Tri-directional atmospheric ambient:\n"
    "        // Top (+Y): Sky illumination\n"
    "        // Bottom (-Y): Ground bounce\n"
    "        // Front (+Z): Direct front fill from camera view, preserving 100% cliff richness\n"
    "        float upWeight = clamp(v_worldNormal.y, 0.0, 1.0);\n"
    "        float downWeight = clamp(-v_worldNormal.y, 0.0, 1.0);\n"
    "        float frontWeight = clamp(abs(v_worldNormal.z), 0.0, 1.0);\n"
    "        float totalWeight = upWeight + downWeight + frontWeight + 1e-4;\n"
    "        upWeight /= totalWeight;\n"
    "        downWeight /= totalWeight;\n"
    "        frontWeight /= totalWeight;\n"
    "\n"
    "        // Biome atmospheric tints:\n"
    "        vec3 skyTint;\n"
    "        vec3 groundTint;\n"
    "        if (u_biomeId == 4) { // Snow / Frost\n"
    "            skyTint = vec3(0.65, 0.78, 0.95);\n"
    "            groundTint = vec3(0.50, 0.58, 0.70);\n"
    "        } else if (u_biomeId == 6) { // Fire / Lava\n"
    "            skyTint = vec3(0.55, 0.40, 0.32);\n"
    "            groundTint = vec3(0.68, 0.32, 0.15);\n"
    "        } else if (u_biomeId == 3 || u_biomeId == 5) { // Underground / Caves\n"
    "            skyTint = vec3(0.35, 0.40, 0.48);\n"
    "            groundTint = vec3(0.40, 0.32, 0.25);\n"
    "        } else if (u_biomeId == 7) { // Corrupted / Dark\n"
    "            skyTint = vec3(0.40, 0.35, 0.55);\n"
    "            groundTint = vec3(0.28, 0.22, 0.35);\n"
    "        } else { // Forest / Plains / Towns (0, 1, 2)\n"
    "            skyTint = vec3(0.58, 0.68, 0.82);\n"
    "            groundTint = vec3(0.38, 0.34, 0.24);\n"
    "        }\n"
    "\n"
    "        // Full ambient intensity — front cliffs receive 100% flat ambient light\n"
    "        vec3 sceneAmb = max(u_globalAmbient.rgb, vec3(0.32));\n"
    "        vec3 skyFill = mix(sceneAmb, skyTint, 0.28);\n"
    "        vec3 groundFill = mix(sceneAmb, groundTint, 0.28);\n"
    "        vec3 cliffFill = sceneAmb * 1.05;\n"
    "\n"
    "        vec3 ambientRadiance = upWeight * skyFill + downWeight * groundFill + frontWeight * cliffFill;\n"
    "        vec3 ambientTerm = baseAlbedo * ambientRadiance * matAmb;\n"
    "        ambientTerm *= mix(kShadowAmbient, vec3(1.0), shadow * 0.35 + 0.65);\n"
    "\n"
    "        vec3 directTerm = baseAlbedo * sunColor * litDiffuse * 0.70;\n"
    "\n"
    "        // Terrain classifier:\n"
    "        float isFrontCliff = smoothstep(0.40, 0.85, abs(v_worldNormal.z));\n"
    "        float isGroundTop = smoothstep(0.15, 0.65, v_worldNormal.y);\n"
    "        float isTerrain = clamp(isGroundTop + isFrontCliff + mat.grassMask, 0.0, 1.0);\n"
    "\n"
    "        // Material-adaptive specular polish (armour, water, stone edges).\n"
    "        vec3 H = normalize(L + V);\n"
    "        float hasShininess = smoothstep(0.5, 5.0, u_shininess);\n"
    "        float spec = pow(max(dot(N, H), 0.0), mat.specPower) * mat.specIntensity * shadow * hasShininess * (1.0 - isTerrain);\n"
    "\n"
    "        // Context-aware fresnel rims: character silhouettes only\n"
    "        float fres = pow(clamp(1.0 - max(dot(N, V), 0.0), 0.0, 1.0), mat.rimPower) * (1.0 - isTerrain);\n"
    "        vec3 rimLight = sunColor * fres * 0.15 * shadow\n"
    "                      + mat.rimColor * fres * kRimStrength * 0.40;\n"
    "\n"
    "        // Backlit foliage transmission (foliage models only, suppressed on terrain)\n"
    "        float sssMult = (u_biomeId == 0 || u_biomeId == 1 || u_biomeId == 2) ? 1.0 : 0.65;\n"
    "        float leafGlow = mat.sssStrength * sssMult * pow(clamp(1.0 - max(dot(N, V), 0.0), 0.0, 1.0), 3.0)\n"
    "                       * clamp(nDotL + 0.20, 0.0, 1.0) * shadow * (1.0 - isTerrain * 0.95);\n"
    "        vec3 foliageLight = mat.sssColor * leafGlow;\n"
    "\n"
    "        // 2.5D dynamic point lights (fire sword glow on hero and rock).\n"
    "        vec3 pointSpec = vec3(0.0);\n"
    "        vec3 pointLightRgb = EvaluatePointLights25D(N, V, v_eyePos, baseAlbedo, shadow, pointSpec);\n"
    "        pointSpec *= (1.0 - isTerrain);\n"
    "\n"
    "        vec3 emitRgb = (u_matEmission.a <= 1.05) ? (u_matEmission.rgb * baseAlbedo) : vec3(0.0);\n"
    "        emitRgb *= (1.0 - 0.85 * isTerrain);\n"
    "\n"
    "        vec3 finalRgb = (ambientTerm + directTerm + pointLightRgb + emitRgb + foliageLight +\n"
    "                         (rimLight + vec3(spec) + pointSpec) * tex.a) * u_alpha;\n"
    "        // Ground luminance governor: soft shoulder so terrain can never burn into neon flat colours.\n"
    "        float gLum = dot(finalRgb, kLuma);\n"
    "        float gCap = 0.46;\n"
    "        float gScale = (gLum > gCap) ? (gCap + (gLum - gCap) * 0.35) / gLum : 1.0;\n"
    "        finalRgb *= mix(1.0, gScale, isTerrain);\n"
    "        float finalAlpha = tex.a * matAlpha * u_alpha;\n"
    "\n"
    "        if (u_flashActive != 0) finalRgb += u_flashColor.rgb * finalAlpha;\n"
    "        fragColor = vec4(finalRgb, finalAlpha);\n"
    "    } else {\n"
    "        // ------------------------------------------------ UNLIT / BACKGROUND / VFX\n"
    "        vec4 c = primary * tex;\n"
    "        if (u_flashActive != 0) c.rgb += u_flashColor.rgb;\n"
    "        c.rgb *= u_alpha;\n"
    "        c.a *= u_alpha;\n"
    "\n"
    "        // Pass tag 2: sky, clouds, snow peaks, hills. Untouched vanilla colours.\n"
    "        if (u_matEmission.a > 1.5 && u_matEmission.a < 2.5) {\n"
    "            fragColor = c;\n"
    "            return;\n"
    "        }\n"
    "        // Pass tag 3: fire sword, magic trails, sparks. Push the hot core into HDR\n"
    "        // and whiten it so bloom turns it into a believable flame / spark glow.\n"
    "        else if (u_matEmission.a > 2.5) {\n"
    "            float luma = dot(c.rgb, kLuma);\n"
    "            float core = smoothstep(0.30, 0.95, luma);\n"
    "            vec3 hot = c.rgb * vec3(1.0, 0.97, 0.90) + vec3(0.10, 0.08, 0.05) * core;\n"
    "            c.rgb = mix(c.rgb, hot, 0.5) * (1.0 + core * 1.35);\n"
    "        }\n"
    "        fragColor = c;\n"
    "    }\n"
    "}\n";

