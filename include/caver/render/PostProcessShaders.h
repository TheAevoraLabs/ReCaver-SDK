static const char* const kPPCompositeFS =
    "#version 330 core\n"
    "// HDR resolve: AO (multi-bounce, bilateral upsample) + bloom + lens CA -> filmic tonemap -> colour grade.\n"
    "uniform sampler2D u_sceneTex;\n"
    "uniform sampler2D u_bloomTex;\n"
    "uniform sampler2D u_aoTex;\n"
    "uniform sampler2D u_depthTex;\n"
    "uniform mat4 u_invProj;\n"
    "uniform vec2 u_aoTexelSize;\n"
    "uniform float u_aoEnabled;\n"
    "uniform float u_bloomIntensity;\n"
    "uniform float u_exposure;\n"
    "uniform float u_vibrance;\n"
    "uniform float u_saturation;\n"
    "uniform float u_contrast;\n"
    "uniform float u_chroma;\n"
    "uniform int u_debugView;\n"
    "uniform int u_biomeId;\n"
    "in vec2 v_texcoord;\n"
    "out vec4 fragColor;\n"
    "\n"
    "const vec3 kLuma = vec3(0.2126, 0.7152, 0.0722);\n"
    "\n"
    "float LinDepth(float d) {\n"
    "    vec4 p = u_invProj * vec4(0.0, 0.0, d * 2.0 - 1.0, 1.0);\n"
    "    return abs(p.z / p.w);\n"
    "}\n"
    "\n"
    "// 2x2 bilateral upsample of the (half-res) AO buffer against full-res depth.\n"
    "float UpsampleAO(vec2 uv) {\n"
    "    vec2 base = uv / u_aoTexelSize - 0.5;\n"
    "    vec2 f = fract(base);\n"
    "    vec2 p0 = (floor(base) + 0.5) * u_aoTexelSize;\n"
    "    float zc = LinDepth(texture(u_depthTex, uv).r);\n"
    "    float tol = 0.040 * zc + 1.2;\n"
    "    float sum = 0.0;\n"
    "    float wsum = 0.0;\n"
    "    for (int y = 0; y < 2; ++y) {\n"
    "        for (int x = 0; x < 2; ++x) {\n"
    "            vec2 suv = p0 + vec2(float(x), float(y)) * u_aoTexelSize;\n"
    "            float wb = (x == 0 ? 1.0 - f.x : f.x) * (y == 0 ? 1.0 - f.y : f.y);\n"
    "            float zs = LinDepth(texture(u_depthTex, suv).r);\n"
    "            float w = wb * exp(-abs(zs - zc) / tol) + 1e-5;\n"
    "            sum += texture(u_aoTex, suv).r * w;\n"
    "            wsum += w;\n"
    "        }\n"
    "    }\n"
    "    return sum / wsum;\n"
    "}\n"
    "\n"
    "// Jimenez et al. multi-bounce approximation: AO keeps the surface hue instead of going grey.\n"
    "vec3 MultiBounceAO(float ao, vec3 albedo) {\n"
    "    vec3 a = 2.0404 * albedo - 0.3324;\n"
    "    vec3 b = -4.7951 * albedo + 0.6417;\n"
    "    vec3 c = 2.7552 * albedo + 0.6903;\n"
    "    return max(vec3(ao), ((ao * a + b) * ao + c) * ao);\n"
    "}\n"
    "\n"
    "// Hue-preserving shoulder (keeps brown rock brown) + highlight desaturation so\n"
    "// HDR flames and sparks roll off to a white-hot core instead of clipping orange.\n"
    "vec3 Tonemap(vec3 c) {\n"
    "    c = max(c, vec3(0.0));\n"
    "    const float start = 0.75;\n"
    "    const float desat = 0.40;\n"
    "    float peak = max(c.r, max(c.g, c.b));\n"
    "    if (peak > start) {\n"
    "        float d = 1.0 - start;\n"
    "        float newPeak = 1.0 - (d * d) / (peak + d - start);\n"
    "        c *= newPeak / peak;\n"
    "        float g = 1.0 - 1.0 / (desat * (peak - newPeak) + 1.0);\n"
    "        c = mix(c, vec3(newPeak), g);\n"
    "    }\n"
    "    return clamp(c, 0.0, 1.0);\n"
    "}\n"
    "\n"
    "vec3 Grade(vec3 c, int biomeId) {\n"
    "    // Smooth contrast around midtone pivot (0.18) — never crushes low-end shadows\n"
    "    float contrastVal = (biomeId == 6) ? (u_contrast * 1.10) : u_contrast;\n"
    "    c = pow(max(c, vec3(0.0)) / 0.18, vec3(mix(0.96, 1.08, contrastVal * 0.5))) * 0.18;\n"
    "    // split-tone: cool shadows, warm highlights\n"
    "    float l = dot(c, kLuma);\n"
    "    vec3 shadowTint = (biomeId == 6) ? vec3(1.04, 0.95, 0.90) :\n"
    "                      (biomeId == 4) ? vec3(0.92, 0.97, 1.08) : vec3(0.95, 0.985, 1.05);\n"
    "    vec3 highlightTint = (biomeId == 4) ? vec3(0.98, 1.01, 1.04) : vec3(1.035, 1.01, 0.955);\n"
    "    vec3 tint = mix(shadowTint, highlightTint, smoothstep(0.12, 0.85, l));\n"
    "    c *= tint;\n"
    "    // vibrance (boost muted colours more than vivid ones) + global saturation\n"
    "    l = dot(c, kLuma);\n"
    "    float maxC = max(c.r, max(c.g, c.b));\n"
    "    float minC = min(c.r, min(c.g, c.b));\n"
    "    float sat = (maxC > 0.001) ? ((maxC - minC) / maxC) : 0.0;\n"
    "    float boost = (1.0 - sat * 0.80) * (u_vibrance - 1.0);\n"
    "    float satMult = (biomeId == 0 || biomeId == 1 || biomeId == 2) ? 1.06 : 1.0;\n"
    "    c = mix(vec3(l), c, (1.0 + boost) * u_saturation * satMult);\n"
    "    // Neon-green tamer: saturated green-dominant colours slide toward natural olive.\n"
    "    float gExcess = c.g - max(c.r, c.b);\n"
    "    float neon = smoothstep(0.05, 0.35, gExcess) * smoothstep(0.30, 0.85, sat);\n"
    "    c = mix(c, vec3(c.r * 1.10, c.g * 0.80, c.b * 0.88), 0.55 * neon);\n"
    "    // Chroma limiter: lava / fire biomes push one channel to the rail and go flat red-pink.\n"
    "    // Pull only the over-saturated, bright pixels back toward their luma, keep the hue.\n"
    "    l = dot(c, kLuma);\n"
    "    maxC = max(c.r, max(c.g, c.b));\n"
    "    minC = min(c.r, min(c.g, c.b));\n"
    "    sat = (maxC > 0.001) ? ((maxC - minC) / maxC) : 0.0;\n"
    "    c = mix(c, vec3(l), 0.32 * smoothstep(0.55, 0.95, sat) * smoothstep(0.30, 0.75, maxC));\n"
    "    // Bright pastel surfaces (ice, snow): restore form with a little mid-tone contrast.\n"
    "    c = mix(c, c * c * (3.0 - 2.0 * c), 0.10 * smoothstep(0.55, 0.9, l));\n"
    "    // Gentle floor lift in the shadows so dark biomes (night forest, caves) keep readable colour.\n"
    "    c += vec3(0.020, 0.024, 0.035) * (1.0 - smoothstep(0.0, 0.35, l));\n"
    "    return clamp(c, 0.0, 1.0);\n"
    "}\n"
    "\n"
    "// Coarse multi-point screen luminance probe for human-eye adaptation (light amount detector)\n"
    "float DetectSceneLuminance(sampler2D sceneTex) {\n"
    "    float lum = 0.0;\n"
    "    lum += dot(texture(sceneTex, vec2(0.50, 0.50)).rgb, kLuma) * 0.28;\n"
    "    lum += dot(texture(sceneTex, vec2(0.35, 0.50)).rgb, kLuma) * 0.12;\n"
    "    lum += dot(texture(sceneTex, vec2(0.65, 0.50)).rgb, kLuma) * 0.12;\n"
    "    lum += dot(texture(sceneTex, vec2(0.50, 0.35)).rgb, kLuma) * 0.12;\n"
    "    lum += dot(texture(sceneTex, vec2(0.50, 0.65)).rgb, kLuma) * 0.12;\n"
    "    lum += dot(texture(sceneTex, vec2(0.25, 0.25)).rgb, kLuma) * 0.06;\n"
    "    lum += dot(texture(sceneTex, vec2(0.75, 0.25)).rgb, kLuma) * 0.06;\n"
    "    lum += dot(texture(sceneTex, vec2(0.25, 0.75)).rgb, kLuma) * 0.06;\n"
    "    lum += dot(texture(sceneTex, vec2(0.75, 0.75)).rgb, kLuma) * 0.06;\n"
    "    return lum;\n"
    "}\n"
    "\n"

    "void main() {\n"
    "    vec2 uv = v_texcoord;\n"
    "\n"
    "    // Radial chromatic aberration, zero at the centre, ~2px at the corners.\n"
    "    vec2 cdir = uv - 0.5;\n"
    "    vec2 coff = cdir * dot(cdir, cdir) * u_chroma;\n"
    "    vec3 scene;\n"
    "    scene.r = texture(u_sceneTex, uv - coff).r;\n"
    "    scene.g = texture(u_sceneTex, uv).g;\n"
    "    scene.b = texture(u_sceneTex, uv + coff).b;\n"
    "    float lum = dot(scene, kLuma);\n"
    "\n"
    "    vec3 bloom = texture(u_bloomTex, uv).rgb;\n"
    "    float ao = (u_aoEnabled > 0.5) ? UpsampleAO(uv) : 1.0;\n"
    "\n"
    "    if (u_debugView == 1) { fragColor = vec4(vec3(ao), 1.0); return; }\n"
    "    if (u_debugView == 2) { fragColor = vec4(min(bloom * u_bloomIntensity * 4.0, vec3(1.0)), 1.0); return; }\n"
    "\n"
    "    // Clean SSAO application: deep, grounded contact shadows without crushing midtones\n"
    "    float aoLift = mix(0.02, 0.08, smoothstep(0.10, 0.80, lum));\n"
    "    ao = mix(ao, 1.0, aoLift);\n"
    "    vec3 aoCol = MultiBounceAO(ao, clamp(scene, 0.0, 1.0));\n"
    "    aoCol = mix(aoCol, vec3(1.0), smoothstep(0.95, 1.6, lum));\n"
    "    // occluded pockets receive cool sky bounce instead of neutral grey (only ever darkens)\n"
    "    aoCol *= mix(vec3(0.84, 0.92, 1.00), vec3(1.0), ao);\n"
    "\n"
    "    // Human-eye adaptation: Light amount detector\n"
    "    float avgSceneLum = DetectSceneLuminance(u_sceneTex);\n"
    "    float localLum = dot(scene, kLuma);\n"
    "    float sceneExcess = clamp((avgSceneLum - 0.44) * 1.5, 0.0, 1.0);\n"
    "    float spotExcess  = clamp((localLum - 0.72) * 1.2, 0.0, 1.0);\n"
    "    float eyeExcess   = clamp(sceneExcess * 0.70 + spotExcess * 0.30, 0.0, 1.0);\n"
    "    float eyeDim      = 1.0 / (1.0 + eyeExcess * 0.22);\n"
    "\n"
    "    // Cool sky fill so deep crevices retain readable tone instead of pure black\n"
    "    float dark = smoothstep(0.30, 0.02, lum) * step(0.0001, lum);\n"
    "    scene += vec3(0.020, 0.028, 0.045) * dark;\n"
    "\n"
    "    vec3 hdr = scene * aoCol + bloom * u_bloomIntensity;\n"
    "    hdr *= u_exposure * eyeDim;\n"
    "    vec3 ldr = Grade(Tonemap(hdr), u_biomeId);\n"
    "    fragColor = vec4(ldr, 1.0);\n"
    "}\n";

static const char* const kPPFinalFS =
    "#version 330 core\n"
    "// Display pass: FXAA 3.x (edge-gated so painted texture detail stays crisp) -> contrast-adaptive\n"
    "// sharpen -> vignette -> film grain + triangular dither (kills sky/vignette banding).\n"
    "uniform sampler2D u_ldrTex;\n"
    "uniform vec2 u_texelSize;\n"
    "uniform float u_fxaa;\n"
    "uniform float u_sharpen;\n"
    "uniform float u_vignette;\n"
    "uniform float u_grain;\n"
    "uniform float u_time;\n"
    "in vec2 v_texcoord;\n"
    "out vec4 fragColor;\n"
    "\n"
    "const vec3 kLuma = vec3(0.299, 0.587, 0.114);\n"
    "\n"
    "float InterleavedGradientNoise(vec2 p) {\n"
    "    vec3 magic = vec3(0.06711056, 0.00583715, 52.9829189);\n"
    "    return fract(magic.z * fract(dot(p, magic.xy)));\n"
    "}\n"
    "\n"
    "vec3 FXAA(vec2 uv) {\n"
    "    vec3 rgbM  = texture(u_ldrTex, uv).rgb;\n"
    "    vec3 rgbNW = texture(u_ldrTex, uv + vec2(-1.0, -1.0) * u_texelSize).rgb;\n"
    "    vec3 rgbNE = texture(u_ldrTex, uv + vec2( 1.0, -1.0) * u_texelSize).rgb;\n"
    "    vec3 rgbSW = texture(u_ldrTex, uv + vec2(-1.0,  1.0) * u_texelSize).rgb;\n"
    "    vec3 rgbSE = texture(u_ldrTex, uv + vec2( 1.0,  1.0) * u_texelSize).rgb;\n"
    "    float lumaM  = dot(rgbM,  kLuma);\n"
    "    float lumaNW = dot(rgbNW, kLuma);\n"
    "    float lumaNE = dot(rgbNE, kLuma);\n"
    "    float lumaSW = dot(rgbSW, kLuma);\n"
    "    float lumaSE = dot(rgbSE, kLuma);\n"
    "    float lumaMin = min(lumaM, min(min(lumaNW, lumaNE), min(lumaSW, lumaSE)));\n"
    "    float lumaMax = max(lumaM, max(max(lumaNW, lumaNE), max(lumaSW, lumaSE)));\n"
    "\n"
    "    // Not an edge: leave the pixel alone.\n"
    "    if (lumaMax - lumaMin < max(0.0312, lumaMax * 0.125)) return rgbM;\n"
    "\n"
    "    vec2 dir;\n"
    "    dir.x = -((lumaNW + lumaNE) - (lumaSW + lumaSE));\n"
    "    dir.y =  ((lumaNW + lumaSW) - (lumaNE + lumaSE));\n"
    "    float dirReduce = max((lumaNW + lumaNE + lumaSW + lumaSE) * (0.25 * (1.0 / 8.0)), 1.0 / 128.0);\n"
    "    float rcpDirMin = 1.0 / (min(abs(dir.x), abs(dir.y)) + dirReduce);\n"
    "    dir = clamp(dir * rcpDirMin, vec2(-8.0), vec2(8.0)) * u_texelSize;\n"
    "\n"
    "    vec3 rgbA = 0.5 * (texture(u_ldrTex, uv + dir * (1.0 / 3.0 - 0.5)).rgb +\n"
    "                       texture(u_ldrTex, uv + dir * (2.0 / 3.0 - 0.5)).rgb);\n"
    "    vec3 rgbB = rgbA * 0.5 + 0.25 * (texture(u_ldrTex, uv + dir * -0.5).rgb +\n"
    "                                     texture(u_ldrTex, uv + dir *  0.5).rgb);\n"
    "    float lumaB = dot(rgbB, kLuma);\n"
    "    return (lumaB < lumaMin || lumaB > lumaMax) ? rgbA : rgbB;\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    vec2 uv = v_texcoord;\n"
    "    vec3 c = (u_fxaa > 0.5) ? FXAA(uv) : texture(u_ldrTex, uv).rgb;\n"
    "\n"
    "    // Unsharp mask against the 4-neighbourhood, clamped so it can never ring.\n"
    "    if (u_sharpen > 0.0) {\n"
    "        vec3 n = texture(u_ldrTex, uv + vec2( u_texelSize.x, 0.0)).rgb\n"
    "               + texture(u_ldrTex, uv + vec2(-u_texelSize.x, 0.0)).rgb\n"
    "               + texture(u_ldrTex, uv + vec2(0.0,  u_texelSize.y)).rgb\n"
    "               + texture(u_ldrTex, uv + vec2(0.0, -u_texelSize.y)).rgb;\n"
    "        c += clamp(c - n * 0.25, vec3(-0.07), vec3(0.07)) * u_sharpen;\n"
    "    }\n"
    "\n"
    "    // Vignette\n"
    "    vec2 q = (uv - 0.5) * vec2(1.15, 1.0);\n"
    "    float vig = smoothstep(0.30, 0.80, length(q));\n"
    "    c *= 1.0 - u_vignette * vig * vig;\n"
    "\n"
    "    // Film grain (mid-tone weighted) + triangular dither\n"
    "    float l = dot(c, kLuma);\n"
    "    vec2 p = gl_FragCoord.xy + fract(u_time) * vec2(113.0, 71.0);\n"
    "    float n1 = InterleavedGradientNoise(p);\n"
    "    float n2 = InterleavedGradientNoise(p + vec2(19.19, 7.77));\n"
    "    float grain = (n1 - 0.5) * u_grain * (1.0 - 0.6 * abs(l * 2.0 - 1.0));\n"
    "    float dither = (n1 + n2 - 1.0) * (1.0 / 255.0);\n"
    "    c += grain + dither;\n"
    "\n"
    "    fragColor = vec4(clamp(c, 0.0, 1.0), 1.0);\n"
    "}\n";

