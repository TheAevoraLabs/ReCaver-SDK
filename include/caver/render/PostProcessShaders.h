    "\n"
    "void main() {\n"
    "    vec3 a = S(vec2(-2.0,  2.0)), b = S(vec2(0.0,  2.0)), c = S(vec2(2.0,  2.0));\n"
    "    vec3 d = S(vec2(-2.0,  0.0)), e = S(vec2(0.0,  0.0)), f = S(vec2(2.0,  0.0));\n"
    "    vec3 g = S(vec2(-2.0, -2.0)), h = S(vec2(0.0, -2.0)), i = S(vec2(2.0, -2.0));\n"
    "    vec3 j = S(vec2(-1.0,  1.0)), k = S(vec2(1.0,  1.0));\n"
    "    vec3 l = S(vec2(-1.0, -1.0)), m = S(vec2(1.0, -1.0));\n"
    "\n"
    "    vec3 g0 = (a + b + d + e) * 0.25;\n"
    "    vec3 g1 = (b + c + e + f) * 0.25;\n"
    "    vec3 g2 = (d + e + g + h) * 0.25;\n"
    "    vec3 g3 = (e + f + h + i) * 0.25;\n"
    "    vec3 g4 = (j + k + l + m) * 0.25;\n"
    "    float w0 = 0.125 * KarisWeight(g0);\n"
    "    float w1 = 0.125 * KarisWeight(g1);\n"
    "    float w2 = 0.125 * KarisWeight(g2);\n"
    "    float w3 = 0.125 * KarisWeight(g3);\n"
    "    float w4 = 0.500 * KarisWeight(g4);\n"
    "    vec3 color = (g0 * w0 + g1 * w1 + g2 * w2 + g3 * w3 + g4 * w4) / (w0 + w1 + w2 + w3 + w4);\n"
    "\n"
    "    float peak = max(color.r, max(color.g, color.b));\n"
    "    float knee = max(u_knee, 0.0001);\n"
    "    float soft = clamp(peak - u_threshold + knee, 0.0, 2.0 * knee);\n"
    "    soft = (soft * soft) / (4.0 * knee);\n"
    "    float contribution = max(soft, peak - u_threshold);\n"
    "    fragColor = vec4(color * (contribution / max(peak, 0.0001)), 1.0);\n"
    "}\n";

