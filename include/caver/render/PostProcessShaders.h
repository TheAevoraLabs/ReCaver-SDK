static const char* const kPPSSAOFS =
    "#version 330 core\n"
    "// Normal-oriented Alchemy-style AO in VIEW space, rebuilt from the real scene projection.\n"
    "//  - real normals from the depth buffer => flat / sloped surfaces can never occlude themselves (no acne)\n"
    "//  - occluder weight = cos(angle to normal) with a world-space falloff => no halos, proper contact pooling\n"
    "//  - ground tops get a bigger, tighter AO; thin small props get a smaller, weaker one\n"
    "uniform sampler2D u_depthTex;\n"
    "uniform vec2  u_texSize;       // AO buffer resolution (half-res)\n"
    "uniform float u_radius;        // screen-space sample radius in UV (0.02)\n"
    "uniform float u_intensity;     // AO strength\n"
    "uniform float u_time;\n"
    "uniform mat4  u_invProj;       // inverse of the projection the world was drawn with\n"
    "uniform float u_power;         // contrast of the final occlusion\n"
    "in vec2 v_texcoord;\n"
    "out vec4 fragColor;\n"
    "\n"
    "// ---------------------------- tuning ----------------------------\n"
    "const int   kSamples       = 20;\n"
    "const float kBiasBase      = 0.16;   // cos-bias: ignores near-coplanar neighbours (anti-acne)\n"
    "const float kBiasGround    = 0.14;   // safe bias on terrain so coplanar ground never falsely self-occludes\n"
    "const float kGroundBoost   = 1.45;   // AO strength multiplier on up-facing ground\n"
    "const float kGroundRadius  = 1.25;   // radius multiplier on ground\n"
    "const float kSmallRadius   = 0.55;   // radius multiplier on thin / small props\n"
    "const float kSmallStrength = 0.50;   // strength multiplier on thin / small props\n"
    "// ----------------------------------------------------------------\n"
    "\n"
    "float IGN(vec2 p) { return fract(52.9829189 * fract(dot(p, vec2(0.06711056, 0.00583715)))); }\n"
    "\n"
    "vec3 ViewPos(vec2 uv, float d) {\n"
    "    vec4 p = u_invProj * vec4(uv * 2.0 - 1.0, d * 2.0 - 1.0, 1.0);\n"
    "    return p.xyz / p.w;\n"
    "}\n"
    "vec3 FetchPos(vec2 uv) { return ViewPos(uv, texture(u_depthTex, uv).r); }\n"
    "\n"
    "vec3 ReconstructNormal(vec2 uv, vec3 P, vec2 px) {\n"
    "    vec3 dx1 = dFdx(P);\n"
    "    vec3 dy1 = dFdy(P);\n"
    "    vec3 pl = FetchPos(uv - vec2(px.x, 0.0));\n"
    "    vec3 pr = FetchPos(uv + vec2(px.x, 0.0));\n"
    "    vec3 pd = FetchPos(uv - vec2(0.0, px.y));\n"
    "    vec3 pu = FetchPos(uv + vec2(0.0, px.y));\n"
    "    vec3 dx2 = (abs(pr.z - P.z) < abs(P.z - pl.z)) ? (pr - P) : (P - pl);\n"
    "    vec3 dy2 = (abs(pu.z - P.z) < abs(P.z - pd.z)) ? (pu - P) : (P - pd);\n"
    "    // Use analytical hardware screen derivatives on continuous surfaces (no quantization lines)\n"
    "    vec3 dx = (abs(dx1.z) < 25.0) ? dx1 : dx2;\n"
    "    vec3 dy = (abs(dy1.z) < 25.0) ? dy1 : dy2;\n"
    "    vec3 n = cross(dx, dy);\n"
    "    float l = length(n);\n"
    "    n = (l > 1e-6) ? n / l : vec3(0.0, 0.0, 1.0);\n"
    "    return (n.z < 0.0) ? -n : n;\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    float depth = texture(u_depthTex, v_texcoord).r;\n"
    "    if (depth > 0.999) { fragColor = vec4(1.0); return; }   // sky / far backdrop\n"
    "\n"
    "    vec2 px = 1.0 / u_texSize;\n"
    "    float aspect = u_texSize.y / u_texSize.x;\n"
    "    vec3 P = ViewPos(v_texcoord, depth);\n"
    "    vec3 N = ReconstructNormal(v_texcoord, P, px);\n"
    "\n"
    "    // up-facing surface (view space +Y ~ world up for this side-on camera)\n"
    "    float isGround = smoothstep(0.45, 0.80, N.y);\n"
    "\n"
    "    // world units covered by one UV step at this depth => scale-free world radius\n"
    "    float worldPerUV = length(ViewPos(v_texcoord + vec2(0.0, 0.01), depth) - P) / 0.01;\n"
    "    // Static spatial interleaved gradient noise — NO temporal jitter so SSAO never crawls or flickers\n"
    "    float jitter = IGN(gl_FragCoord.xy);\n"
    "\n"
    "    // ---- small / thin prop detector: wide ring, count samples far BEHIND the tangent plane ----\n"
    "    float behind = 0.0;\n"
    "    float R0 = u_radius * worldPerUV;\n"
    "    for (int k = 0; k < 8; ++k) {\n"
    "        float a = (float(k) + jitter) * 0.7853982;\n"
    "        vec2 o = vec2(cos(a), sin(a)) * u_radius * 2.5;\n"
    "        o.x *= aspect;\n"
    "        vec3 S = FetchPos(v_texcoord + o);\n"
    "        behind += step(dot(S - P, N), -1.2 * R0);\n"
    "    }\n"
    "    float smallness = smoothstep(0.30, 0.70, behind / 8.0) * (1.0 - isGround);\n"
    "\n"
    "    float ruv = u_radius * mix(1.0, kGroundRadius, isGround) * mix(1.0, kSmallRadius, smallness);\n"
    "    float Rw  = max(ruv * worldPerUV, 1e-4);\n"
    "    float strength = u_intensity * mix(1.0, kGroundBoost, isGround) * mix(1.0, kSmallStrength, smallness);\n"
    "    float bias = mix(kBiasBase, kBiasGround, isGround);\n"
    "\n"
    "    float occ = 0.0;\n"
    "    for (int i = 0; i < kSamples; ++i) {\n"
    "        float fi = float(i) + 0.5;\n"
    "        float rr = sqrt(fi / float(kSamples));\n"
    "        float th = fi * 2.39996323 + jitter * 6.2831853;\n"
    "        vec2 off = vec2(cos(th), sin(th)) * rr * ruv;\n"
    "        off.x *= aspect;\n"
    "        vec3 v = FetchPos(v_texcoord + off) - P;\n"
    "        float vv = dot(v, v);\n"
    "        float cosA = dot(v, N) * inversesqrt(max(vv, 1e-12));\n"
    "        float fall = 1.0 - clamp(vv / (Rw * Rw), 0.0, 1.0);\n"
    "        occ += max(cosA - bias, 0.0) * fall * fall;\n"
    "    }\n"
    "    occ /= float(kSamples);\n"
    "\n"
    "    float ao = clamp(1.0 - occ * 2.4 * strength, 0.0, 1.0);\n"
    "    ao = pow(ao, u_power);\n"
    "    fragColor = vec4(ao, ao, ao, 1.0);\n"
    "}\n";

static const char* const kPPAOBlurFS =
    "#version 330 core\n"
    "// Depth-aware (bilateral) 9-tap blur: smooths SSAO jitter without bleeding across silhouettes.\n"
    "uniform sampler2D u_aoTex;\n"
    "uniform sampler2D u_depthTex;\n"
    "uniform mat4 u_invProj;\n"
    "uniform vec2 u_direction;      // (1/w, 0) or (0, 1/h)\n"
    "in vec2 v_texcoord;\n"
    "out vec4 fragColor;\n"
    "\n"
    "float LinZ(vec2 uv) {\n"
    "    vec4 p = u_invProj * vec4(0.0, 0.0, texture(u_depthTex, uv).r * 2.0 - 1.0, 1.0);\n"
    "    return abs(p.z / p.w);\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    const float w[5] = float[5](0.2270, 0.1945, 0.1216, 0.0540, 0.0162);\n"
    "    float zc = LinZ(v_texcoord);\n"
    "    float tol = 0.040 * zc + 1.2;\n"
    "    float sum = texture(u_aoTex, v_texcoord).r * w[0];\n"
    "    float wsum = w[0];\n"
    "    for (int i = 1; i < 5; ++i) {\n"
    "        for (int s = -1; s <= 1; s += 2) {\n"
    "            vec2 uv = v_texcoord + u_direction * float(i * s) * 1.35;\n"
    "            float wi = w[i] * exp(-abs(LinZ(uv) - zc) / tol);\n"
    "            sum += texture(u_aoTex, uv).r * wi;\n"
    "            wsum += wi;\n"
    "        }\n"
    "    }\n"
    "    float a = sum / wsum;\n"
    "    fragColor = vec4(a, a, a, 1.0);\n"
    "}\n";

